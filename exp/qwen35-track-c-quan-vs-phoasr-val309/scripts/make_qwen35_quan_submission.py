from __future__ import annotations

import argparse
import gc
import hashlib
import json
import os
import sys
import time
import urllib.request
from pathlib import Path

import _bootstrap  # noqa: F401
from inference_common import read_audio_16k
from lifemate.agent import Agent
from lifemate.asr import PhoASRModel
from lifemate.pipeline import LifeMatePipeline
from lifemate.utils import find_data_root, load_jsonl, resolve_audio, seed_everything


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def ollama_version() -> str:
    host = os.environ.get("OLLAMA_HOST", "http://127.0.0.1:11434").rstrip("/")
    with urllib.request.urlopen(host + "/api/version", timeout=10) as response:
        return json.loads(response.read().decode("utf-8"))["version"]


def read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    project = _bootstrap.ROOT
    parser = argparse.ArgumentParser(description="Create a Track C public-test submission with QUAN FT + KenLM beam32")
    parser.add_argument("--data-root", default="train+public_test/train+public_test")
    parser.add_argument("--quan-model", default="exp/quan-transcribe-lifemate-domain-v1/output/model")
    parser.add_argument("--lm", default="models/quan-transcribe/lm")
    parser.add_argument("--beam-width", type=int, default=32)
    parser.add_argument("--ollama-model", default="qwen3.5:4b-q4_K_M")
    parser.add_argument("--output", default="outputs/submissions/qwen35-track-c-quan-ft-beam32-public-test.jsonl")
    parser.add_argument("--resume", action="store_true")
    args = parser.parse_args()
    if args.beam_width != 32:
        parser.error("This branch is fixed to the validated KenLM beam32 decoder")

    seed_everything()
    root = find_data_root(args.data_root)
    split = "public_test"
    split_dir = root / split
    items = list(load_jsonl(split_dir / f"{split}.jsonl"))
    ids = [item["id"] for item in items]
    model_dir = Path(args.quan_model)
    lm_dir = Path(args.lm)
    audit_path = model_dir / "dataset-audit.json"
    audit = json.loads(audit_path.read_text(encoding="utf-8"))
    if audit.get("train_ids") != 1236 or audit.get("train_validation_overlap") != 0:
        raise RuntimeError("QUAN checkpoint audit does not certify the fixed train-only 1,236-ID fine-tune")
    lm_config_path = lm_dir / "lm_config.json"
    lm_config = json.loads(lm_config_path.read_text(encoding="utf-8"))
    if float(lm_config.get("alpha", -1)) != 0.3 or float(lm_config.get("beta", -1)) != 1.0:
        raise RuntimeError(f"Unexpected KenLM alpha/beta config: {lm_config}")

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    artifact_dir = Path("exp/qwen35-track-c-quan-vs-phoasr-val309/output/submission-artifacts")
    artifact_dir.mkdir(parents=True, exist_ok=True)
    transcript_path = artifact_dir / (output.stem + "_transcripts.jsonl")
    transcript_manifest_path = artifact_dir / (output.stem + "_transcripts_manifest.json")
    diagnostics_path = artifact_dir / (output.stem + "_predictions.jsonl")
    manifest_path = artifact_dir / (output.stem + "_manifest.json")
    if output.exists() and not args.resume:
        raise SystemExit(f"Refusing to overwrite {output}; use --resume")

    transcript_rows = read_jsonl(transcript_path)
    transcript_done = [row["id"] for row in transcript_rows]
    if transcript_done != ids[:len(transcript_done)]:
        raise RuntimeError("Existing transcript cache is not an ordered public-test prefix")
    if transcript_path.exists() and len(transcript_rows) == len(ids):
        cached_manifest = json.loads(transcript_manifest_path.read_text(encoding="utf-8"))
        if cached_manifest.get("checkpoint") != str(model_dir) or cached_manifest.get("beam_width") != 32:
            raise RuntimeError("Transcript cache was generated by a different checkpoint/decoder")
    else:
        inference_dir = Path("models/quan-transcribe/inference").resolve()
        if not inference_dir.is_dir():
            raise FileNotFoundError(f"QUAN inference package is missing: {inference_dir}")
        sys.path.insert(0, str(inference_dir))
        from quan_transcribe import QuanTranscribe

        asr = QuanTranscribe.from_pretrained(str(model_dir), device=None, lm=str(lm_dir))
        rows_by_id = {row["id"]: row for row in transcript_rows}
        for index, item in enumerate(items[len(transcript_rows):], start=len(transcript_rows) + 1):
            audio = resolve_audio(root, split_dir, item, item["audio"])
            waveform = read_audio_16k(audio)
            started = time.perf_counter()
            text = asr.transcribe(waveform, sample_rate=16000, streaming=False,
                                  use_lm=True, beam_width=args.beam_width)
            rows_by_id[item["id"]] = {"id": item["id"], "transcript": text,
                                       "inference_seconds": time.perf_counter() - started,
                                       "decoder": "KenLM CTC beam search", "beam_width": args.beam_width}
            if index % 25 == 0 or index == len(items):
                ordered = [rows_by_id[sid] for sid in ids if sid in rows_by_id]
                transcript_path.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in ordered),
                                           encoding="utf-8")
                print(f"[QUAN transcripts {index}/{len(items)}] {item['id']}", flush=True)
        transcript_rows = [rows_by_id[sid] for sid in ids]
        transcript_path.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in transcript_rows),
                                   encoding="utf-8")
        del asr
        gc.collect()
        try:
            import torch
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
        except ImportError:
            pass
        write_json(transcript_manifest_path, {"split": split, "samples": len(ids),
            "checkpoint": str(model_dir), "checkpoint_weights_sha256": sha256(model_dir / "model.safetensors"),
            "dataset_audit": str(audit_path), "train_ids": audit["train_ids"],
            "train_validation_overlap": audit["train_validation_overlap"], "validation_policy": audit["validation_policy"],
            "decoder": "KenLM CTC beam search", "beam_width": 32, "lm": str(lm_dir),
            "lm_config": lm_config, "lm_config_sha256": sha256(lm_config_path),
            "transcripts": str(transcript_path), "transcript_sha256": sha256(transcript_path)})

    cached_ids = [row["id"] for row in transcript_rows]
    if cached_ids != ids:
        raise RuntimeError(f"Transcript cache incomplete: {len(cached_ids)}/{len(ids)}")
    transcripts = {row["id"]: row["transcript"] for row in transcript_rows}
    if output.exists() and not args.resume:
        raise SystemExit(f"Refusing to overwrite {output}; use --resume")
    prior = read_jsonl(output)
    prior_diag = read_jsonl(diagnostics_path)
    if len(prior) != len(prior_diag) or len(prior) > len(items):
        raise RuntimeError("Cannot resume: submission and prediction sidecar are not aligned")
    for index, row in enumerate(prior):
        if row.get("id") != ids[index] or set(row) != {"id", "tool_calls", "state_hash"}:
            raise RuntimeError(f"Cannot resume from invalid submission prefix at row {index + 1}")
    if prior and not args.resume:
        raise SystemExit(f"Refusing to overwrite {output}; use --resume")

    version = ollama_version()
    os.environ["LIFEMATE_LLM_BACKEND"] = "ollama"
    os.environ["LIFEMATE_OLLAMA_MODEL"] = args.ollama_model
    os.environ["LIFEMATE_OLLAMA_CONTEXT"] = "8192"
    os.environ["LIFEMATE_OLLAMA_NUM_PREDICT"] = "512"
    os.environ["LIFEMATE_OLLAMA_THINK"] = "true"
    os.environ["LIFEMATE_OLLAMA_PROTOCOL"] = "json"
    os.environ["LIFEMATE_PROMPT_LANGUAGE"] = "en"
    agent = Agent(max_new_tokens=512, context_limit=8192, ollama_thinking=True, ollama_native_tools=False)
    # Match Track C history transcription behavior; current-turn transcript is the QUAN cache above.
    pipeline = LifeMatePipeline(root, split, asr=PhoASRModel(), agent=agent, max_steps=5)
    started = time.perf_counter()
    runtime_failures = sum(bool(row.get("runtime_error")) for row in prior_diag)
    mode = "a" if prior else "w"
    with output.open(mode, encoding="utf-8", newline="\n") as submission, \
            diagnostics_path.open(mode, encoding="utf-8", newline="\n") as diagnostics:
        for index in range(len(prior), len(items)):
            item = items[index]
            item_started = time.perf_counter()
            try:
                result = pipeline.run(item, transcript_override=transcripts[item["id"]])
                calls = [{"name": c.get("name"), "arguments": c.get("arguments", {})} for c in result["tool_calls"]]
                row = {"id": item["id"], "tool_calls": calls, "state_hash": result["state_hash"]}
                detail = {"id": item["id"], "transcript_used": transcripts[item["id"]],
                          "tool_calls": calls, "state_hash": result["state_hash"],
                          "observations": result["observations"], "model_output": result["model_output"],
                          "latency_seconds": result["latency_seconds"], "runtime_error": None}
            except Exception as exc:
                runtime_failures += 1
                latency = time.perf_counter() - item_started
                row = {"id": item["id"], "tool_calls": [], "state_hash": "0" * 64}
                detail = {"id": item["id"], "transcript_used": transcripts[item["id"]],
                          "tool_calls": [], "state_hash": row["state_hash"], "observations": [],
                          "model_output": [], "latency_seconds": latency,
                          "runtime_error": f"{type(exc).__name__}: {exc}"}
            submission.write(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n")
            diagnostics.write(json.dumps(detail, ensure_ascii=False, separators=(",", ":")) + "\n")
            submission.flush(); diagnostics.flush()
            print(f"[{index + 1}/{len(items)}] {item['id']} calls={len(row['tool_calls'])} "
                  f"latency={detail['latency_seconds']:.2f}s error={detail['runtime_error']}", flush=True)

    manifest = {"split": split, "rows": len(items), "submission": str(output),
        "diagnostics": str(diagnostics_path), "transcripts": str(transcript_path),
        "transcript_sha256": sha256(transcript_path), "transcript_manifest": str(transcript_manifest_path),
        "asr": "QUAN Transcribe LifeMate fine-tune + KenLM CTC beam search", "asr_checkpoint": str(model_dir),
        "asr_checkpoint_sha256": sha256(model_dir / "model.safetensors"), "beam_width": 32,
        "lm": str(lm_dir), "lm_config": lm_config, "lm_config_sha256": sha256(lm_config_path),
        "llm_backend": "Ollama", "llm_model": args.ollama_model, "ollama_version": version,
        "llm_parameters": "4.2B", "quantization": "Q4_K_M", "prompt_version": "observation-grounded-v2",
        "prompt_language": "en", "thinking": True, "protocol": "JSON; native tool calling disabled",
        "temperature": 0, "num_predict": 512, "num_ctx": 8192, "max_action_turns": 5,
        "toolenv_sessions": "exactly one per sample", "runtime_failures_this_run": runtime_failures,
        "elapsed_seconds_this_run": time.perf_counter() - started,
        "public_lb_submitted": False, "note": "Local submission artifact only; no leaderboard submission."}
    write_json(manifest_path, manifest)
    print(json.dumps(manifest, ensure_ascii=False, indent=2))
    return 1 if runtime_failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
